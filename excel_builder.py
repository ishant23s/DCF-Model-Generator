"""
Builds the downloadable DCF workbook with LIVE Excel formulas.

Change any yellow input cell and the whole model recalculates:
Inputs -> WACC -> Forecast & FCFF -> Valuation.

The Sensitivity sheet is a static snapshot computed by the app
(Excel What-If data tables cannot be generated by openpyxl).
"""

from __future__ import annotations

import io

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill, Border, Side
from openpyxl.utils import get_column_letter

from dcf_core import Assumptions, CompanyData

YELLOW = PatternFill("solid", fgColor="FFF7DC")
BLUE = PatternFill("solid", fgColor="DCE9F7")
GREY = PatternFill("solid", fgColor="F2F2F2")
TITLE_FONT = Font(bold=True, size=14)
HEAD_FONT = Font(bold=True, size=11)
BOLD = Font(bold=True)
THIN = Border(bottom=Side(style="thin", color="BFBFBF"))
MONEY = '#,##0'
PCT = '0.0%'


def _put(ws, cell, value, font=None, fill=None, fmt=None, border=None):
    c = ws[cell]
    c.value = value
    if font:
        c.font = font
    if fill:
        c.fill = fill
    if fmt:
        c.number_format = fmt
    if border:
        c.border = border
    return c


def build_workbook(data: CompanyData, a: Assumptions, result: dict,
                   wacc_info: dict, sensitivity: dict | None = None) -> io.BytesIO:
    wb = Workbook()
    wb.calculation.fullCalcOnLoad = True  # Excel/LibreOffice recalc on open

    # ---------------------------------------------------------------- About
    ws = wb.active
    ws.title = "About"
    ws.sheet_properties.pageSetUpPr = None
    ws.column_dimensions["A"].width = 110
    lines = [
        ("DCF Model Generator", TITLE_FONT),
        (f"Company: {data.name} ({data.ticker})", HEAD_FONT),
        ("", None),
        ("HOW TO USE", HEAD_FONT),
        ("1. Yellow cells on the Inputs and WACC sheets are the only cells you need to touch.", None),
        ("2. Change growth, margin, WACC or terminal growth and the Valuation updates automatically - every number in this workbook is a live Excel formula.", None),
        ("3. The Sensitivity sheet is a fixed snapshot made when this file was generated.", None),
        ("", None),
        ("WHERE THE NUMBERS COME FROM (auto mode)", HEAD_FONT),
        ("Latest annual financial statements (revenue, EBIT, tax, depreciation, capex, debt, cash), share price, shares outstanding and beta - pulled free from Yahoo Finance, which republishes the company's reported annual-report financials. Defaults: growth = revenue CAGR of the available history, margin = latest EBIT margin, capex/depreciation = average % of revenue, working capital = latest balance-sheet level as % of revenue. Beta sanity check: Yahoo's beta is broken for some stocks (even negative), so if it falls outside 0.2-2.0 a default of 0.7 (India) / 1.0 (global) is used - edit it on the WACC sheet. If FCFF comes out negative, the model is telling you the company reinvests more than it earns at these assumptions (common for fast growers) - test your own growth/capex view in the yellow cells.", None),
        ("In manual mode every number was typed by the user.", None),
        ("", None),
        ("DISCLAIMER", HEAD_FONT),
        ("This is an educational model, not investment advice and not a recommendation to buy or sell any security. A DCF is only as good as its assumptions - check them against the company's actual annual report before using the output for any decision.", None),
    ]
    if data.is_financial:
        lines += [
            ("", None),
            ("WARNING - FINANCIAL COMPANY", Font(bold=True, size=12, color="C00000")),
            ("This company is in the financial sector (bank / NBFC / insurance). A free-cash-flow-to-firm (FCFF) DCF is generally NOT the right way to value financial firms, because debt and working capital are part of their core business. Treat this output as a rough illustration only; dividend-discount or residual-income models are normally used instead.", Font(color="C00000")),
        ]
    for i, (text, font) in enumerate(lines, start=1):
        c = _put(ws, f"A{i}", text, font=font)
        c.alignment = Alignment(wrap_text=True, vertical="top")
        ws.row_dimensions[i].height = 30 if len(text) > 110 else 16

    # ---------------------------------------------------------------- Inputs
    ws = wb.create_sheet("Inputs")
    ws.column_dimensions["A"].width = 42
    ws.column_dimensions["B"].width = 22
    ws.column_dimensions["C"].width = 46
    _put(ws, "A1", "Inputs", TITLE_FONT)
    _put(ws, "A2", "Yellow cells = type / change these. Everything else is a formula.", Font(italic=True))
    rows = [
        (3, "Company name", data.name, None, None),
        (4, "Ticker", data.ticker, None, None),
        (5, "Currency / unit", f"{data.currency} - money in {data.unit_label}, price per share in {data.currency}", None, None),
        (6, "Current share price", data.current_price, MONEY, "Market price per share"),
        (7, "Shares outstanding", data.shares, MONEY, f"In {data.unit_label.split()[-1]} of shares (same unit as money)"),
        (8, "Total debt", data.total_debt, MONEY, f"{data.unit_label}"),
        (9, "Cash & equivalents", data.cash, MONEY, f"{data.unit_label}"),
        (10, "Net debt (Debt - Cash)", "=B8-B9", MONEY, "Formula"),
        (12, "Operating assumptions", None, None, None),
        (13, "Base revenue (latest actual)", data.base_revenue, MONEY, f"{data.unit_label}"),
        (14, "Revenue growth (per year)", a.revenue_growth, PCT, "Default: historical revenue CAGR (auto mode)"),
        (15, "EBIT margin", a.ebit_margin, PCT, "Default: latest actual EBIT margin"),
        (16, "Tax rate", a.tax_rate, PCT, "Default: latest effective tax rate"),
        (17, "Depreciation & amortisation (% of revenue)", a.da_pct_revenue, PCT, ""),
        (18, "Capex (% of revenue)", a.capex_pct_revenue, PCT, ""),
        (19, "Working capital (% of revenue, level)", a.wc_pct_revenue, PCT, "Each year's WC investment = this % x revenue increase"),
        (20, "Forecast years", a.forecast_years, '0', ""),
        (21, "Terminal growth", a.terminal_growth, PCT, "Perpetual growth after the forecast period"),
    ]
    input_rows = {6, 7, 8, 9, 13, 14, 15, 16, 17, 18, 19, 20, 21}
    for r, label, value, fmt, note in rows:
        if r == 12:
            _put(ws, f"A{r}", label, HEAD_FONT, GREY)
            continue
        _put(ws, f"A{r}", label, BOLD if r in (10,) else None)
        if value is not None:
            _put(ws, f"B{r}", value, fill=YELLOW if r in input_rows else None, fmt=fmt)
        if note:
            _put(ws, f"C{r}", note, Font(italic=True, size=9))

    # ---------------------------------------------------------------- WACC
    ws = wb.create_sheet("WACC")
    ws.column_dimensions["A"].width = 42
    ws.column_dimensions["B"].width = 22
    ws.column_dimensions["C"].width = 46
    _put(ws, "A1", "WACC (discount rate)", TITLE_FONT)
    _put(ws, "A3", "Risk-free rate", BOLD)
    _put(ws, "B3", a.risk_free_rate, fill=YELLOW, fmt=PCT)
    _put(ws, "C3", "Default: India 10Y govt bond ~7.1% / US 10Y ~4.3%", Font(italic=True, size=9))
    _put(ws, "A4", "Equity risk premium")
    _put(ws, "B4", a.equity_risk_premium, fill=YELLOW, fmt=PCT)
    _put(ws, "A5", "Beta")
    _put(ws, "B5", a.beta, fill=YELLOW, fmt='0.00')
    _put(ws, "A6", "Cost of equity = Rf + Beta x ERP", BOLD)
    _put(ws, "B6", "=B3+B5*B4", fill=BLUE, fmt=PCT)
    _put(ws, "A7", "Pre-tax cost of debt")
    _put(ws, "B7", a.pretax_cost_of_debt, fill=YELLOW, fmt=PCT)
    _put(ws, "A8", "Tax rate", BOLD)
    _put(ws, "B8", "=Inputs!B16", fmt=PCT)
    _put(ws, "A9", "After-tax cost of debt", BOLD)
    _put(ws, "B9", "=B7*(1-B8)", fill=BLUE, fmt=PCT)
    _put(ws, "A10", "Market value of equity (Price x Shares)")
    _put(ws, "B10", "=Inputs!B6*Inputs!B7", fmt=MONEY)
    _put(ws, "A11", "Debt (book value)")
    _put(ws, "B11", "=Inputs!B8", fmt=MONEY)
    _put(ws, "A12", "Weight of equity")
    _put(ws, "B12", "=IF((B10+B11)=0,1,B10/(B10+B11))", fmt=PCT)
    _put(ws, "A13", "Weight of debt")
    _put(ws, "B13", "=1-B12", fmt=PCT)
    _put(ws, "A14", "WACC", Font(bold=True, size=12))
    _put(ws, "B14", "=B6*B12+B9*B13", fill=BLUE, fmt=PCT)

    # ---------------------------------------------------------------- Forecast
    ws = wb.create_sheet("Forecast & FCFF")
    ws.column_dimensions["A"].width = 34
    for col in range(2, 8):
        ws.column_dimensions[get_column_letter(col)].width = 17
    _put(ws, "A1", "Forecast & Free Cash Flow to Firm (FCFF)", TITLE_FONT)
    _put(ws, "A3", "Item", HEAD_FONT, GREY)
    _put(ws, "B3", "Base Year", HEAD_FONT, GREY)
    for t in range(1, 6):
        _put(ws, f"{get_column_letter(2+t)}3", f"Year {t}", HEAD_FONT, GREY)
    labels = {
        4: "Revenue",
        5: "EBIT",
        6: "Less: Tax",
        7: "NOPAT",
        8: "Add: Depreciation & amortisation",
        9: "Less: Capex",
        10: "Less: Increase in working capital",
        11: "Free Cash Flow to Firm (FCFF)",
        12: "Discount factor",
        13: "PV of FCFF",
    }
    for r, label in labels.items():
        _put(ws, f"A{r}", label, BOLD if r in (11, 13) else None)
    # Base year column B
    _put(ws, "B4", "=Inputs!B13", fmt=MONEY)
    _put(ws, "B5", "=B4*Inputs!$B$15", fmt=MONEY)
    _put(ws, "B6", "=B5*Inputs!$B$16", fmt=MONEY)
    _put(ws, "B7", "=B5-B6", fmt=MONEY)
    _put(ws, "B8", "=B4*Inputs!$B$17", fmt=MONEY)
    _put(ws, "B9", "=B4*Inputs!$B$18", fmt=MONEY)
    _put(ws, "B10", 0, fmt=MONEY)
    _put(ws, "B11", "=B7+B8-B9-B10", fmt=MONEY)
    # Forecast columns C..G
    for idx in range(5):
        col = get_column_letter(3 + idx)
        prev = get_column_letter(2 + idx)
        _put(ws, f"{col}4", f"={prev}4*(1+Inputs!$B$14)", fmt=MONEY)
        _put(ws, f"{col}5", f"={col}4*Inputs!$B$15", fmt=MONEY)
        _put(ws, f"{col}6", f"={col}5*Inputs!$B$16", fmt=MONEY)
        _put(ws, f"{col}7", f"={col}5-{col}6", fmt=MONEY)
        _put(ws, f"{col}8", f"={col}4*Inputs!$B$17", fmt=MONEY)
        _put(ws, f"{col}9", f"={col}4*Inputs!$B$18", fmt=MONEY)
        _put(ws, f"{col}10", f"=Inputs!$B$19*({col}4-{prev}4)", fmt=MONEY)
        _put(ws, f"{col}11", f"={col}7+{col}8-{col}9-{col}10", fmt=MONEY)
        _put(ws, f"{col}12", f"=1/(1+WACC!$B$14)^(COLUMN()-2)", fmt='0.0000')
        _put(ws, f"{col}13", f"={col}11*{col}12", fmt=MONEY)
    for r in (11, 13):
        for col in range(1, 8):
            ws.cell(row=r, column=col).fill = BLUE

    # ---------------------------------------------------------------- Valuation
    ws = wb.create_sheet("Valuation")
    ws.column_dimensions["A"].width = 42
    ws.column_dimensions["B"].width = 22
    _put(ws, "A1", "Valuation", TITLE_FONT)
    vrows = [
        (3, "PV of FCFF (Years 1-5)", "=SUM('Forecast & FCFF'!C13:G13)", MONEY),
        (4, "FCFF in final forecast year", "='Forecast & FCFF'!G11", MONEY),
        (5, "Terminal growth", "=Inputs!B21", PCT),
        (6, "WACC", "=WACC!B14", PCT),
        (7, "Terminal Value", "=B4*(1+B5)/(B6-B5)", MONEY),
        (8, "Discount factor (final year)", "='Forecast & FCFF'!G12", '0.0000'),
        (9, "PV of Terminal Value", "=B7*B8", MONEY),
        (10, "Enterprise Value", "=B3+B9", MONEY),
        (11, "Less: Net debt", "=Inputs!B10", MONEY),
        (12, "Equity Value", "=B10-B11", MONEY),
        (13, "Shares outstanding", "=Inputs!B7", MONEY),
        (14, "Value per share", "=IF(B13=0,0,B12/B13)", '#,##0.00'),
        (15, "Current price", "=Inputs!B6", '#,##0.00'),
        (16, "Upside / (downside)", "=IF(B15=0,0,B14/B15-1)", PCT),
    ]
    for r, label, formula, fmt in vrows:
        _put(ws, f"A{r}", label, BOLD if r in (10, 12, 14, 16) else None)
        _put(ws, f"B{r}", formula, fill=BLUE if r in (14,) else None, fmt=fmt)

    # ---------------------------------------------------------------- History
    if data.history_years:
        ws = wb.create_sheet("History")
        ws.column_dimensions["A"].width = 26
        for col in range(2, 2 + len(data.history_years)):
            ws.column_dimensions[get_column_letter(col)].width = 16
        _put(ws, "A1", "Historical financials (as reported, annual)", TITLE_FONT)
        _put(ws, "A3", "Item", HEAD_FONT, GREY)
        for i, y in enumerate(data.history_years):
            _put(ws, f"{get_column_letter(2+i)}3", str(y), HEAD_FONT, GREY)
        for r, (label, series) in enumerate([
            ("Revenue", data.history_revenue),
            ("EBIT", data.history_ebit),
            ("Net income", data.history_net_income),
        ], start=4):
            _put(ws, f"A{r}", label, BOLD)
            for i, v in enumerate(series):
                if v is not None:
                    _put(ws, f"{get_column_letter(2+i)}{r}", v, fmt=MONEY)
        _put(ws, f"A{r+2}", f"Money in {data.unit_label}. Source: Yahoo Finance (company reported annual financials).", Font(italic=True, size=9))

    # ---------------------------------------------------------------- Sensitivity
    if sensitivity:
        ws = wb.create_sheet("Sensitivity")
        ws.column_dimensions["A"].width = 18
        g_vals = sensitivity["g_values"]
        _put(ws, "A1", "Sensitivity: Value per share", TITLE_FONT)
        _put(ws, "A2", "Rows = WACC, Columns = terminal growth. Static snapshot from generation time - change Inputs/WACC for a live re-run.", Font(italic=True, size=9))
        _put(ws, "A4", "WACC \\ g", HEAD_FONT, GREY)
        for j, g in enumerate(g_vals):
            _put(ws, f"{get_column_letter(2+j)}4", g, HEAD_FONT, GREY, fmt=PCT)
        for i, w in enumerate(sensitivity["wacc_values"]):
            r = 5 + i
            _put(ws, f"A{r}", w, BOLD, GREY, fmt=PCT)
            for j, g in enumerate(g_vals):
                v = sensitivity["grid"][w][g]
                if v is not None:
                    _put(ws, f"{get_column_letter(2+j)}{r}", round(v, 2), fmt='#,##0.00')

    buf = io.BytesIO()
    wb.save(buf)
    buf.seek(0)
    return buf
